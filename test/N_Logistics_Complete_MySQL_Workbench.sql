-- ============================================================================
-- N LOGISTICS MANAGEMENT SYSTEM - COMPLETE MYSQL WORKBENCH SCRIPT
-- SRS coverage: FR1-FR7 + AI audit logging
-- Target: MySQL 8.0.16+ / XAMPP MySQL 8 / InnoDB
-- Architecture: Java Servlet -> DAO/JDBC PreparedStatement -> MySQL
--
-- IMPORTANT:
-- 1) This script creates the database if absent. It DOES NOT DROP existing data.
-- 2) Run on a NEW/EMPTY n_logistic_db for the cleanest first installation.
-- 3) If tables already exist, back up your database and use a fresh schema name;
--    CREATE TABLE IF NOT EXISTS does not migrate old table definitions.
-- 4) Store password hashes generated by Java (BCrypt/Argon2), never plain passwords.
-- 5) File binaries should be stored on the server; keep only safe metadata/path here.
-- 6) Booking, payment and claim settlement are transactional. Call procedures via JDBC.
-- ============================================================================

CREATE DATABASE IF NOT EXISTS n_logistic_db
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE n_logistic_db;
SET NAMES utf8mb4;

-- ============================================================================
-- FR1 - COMPANIES, USERS, CUSTOMER PROFILES, AUDIT, PORTS, VESSELS
-- ============================================================================
CREATE TABLE companies (
  company_id INT AUTO_INCREMENT PRIMARY KEY,
  company_name VARCHAR(150) NOT NULL,
  company_type ENUM('CONSUMER','SELLER') NOT NULL,
  gst_number VARCHAR(20) UNIQUE,
  iec_code VARCHAR(20),
  address TEXT, city VARCHAR(60), country VARCHAR(60),
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE users (
  user_id INT AUTO_INCREMENT PRIMARY KEY,
  company_id INT NULL,
  role ENUM('ADMIN','CONSUMER','SELLER') NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  phone VARCHAR(25),
  status ENUM('ACTIVE','INACTIVE','LOCKED') NOT NULL DEFAULT 'ACTIVE',
  failed_attempts INT NOT NULL DEFAULT 0,
  last_login DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_company FOREIGN KEY(company_id) REFERENCES companies(company_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  INDEX idx_users_role_status(role,status), INDEX idx_users_company(company_id)
) ENGINE=InnoDB;

CREATE TABLE customers (
  customer_id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL UNIQUE,
  company_id INT NOT NULL,
  contact_person VARCHAR(100), billing_address TEXT,
  credit_limit DECIMAL(14,2) NOT NULL DEFAULT 0,
  CONSTRAINT fk_customers_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT fk_customers_company FOREIGN KEY(company_id) REFERENCES companies(company_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE audit_log (
  log_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NULL, action VARCHAR(100) NOT NULL,
  table_name VARCHAR(64), record_id BIGINT,
  old_value JSON NULL, new_value JSON NULL,
  ip_address VARCHAR(45), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_audit_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE SET NULL,
  INDEX idx_audit_created(created_at), INDEX idx_audit_record(table_name,record_id)
) ENGINE=InnoDB;

CREATE TABLE ports (
  port_id INT AUTO_INCREMENT PRIMARY KEY,
  port_code VARCHAR(10) NOT NULL UNIQUE,
  port_name VARCHAR(100) NOT NULL,
  city VARCHAR(60), country VARCHAR(60),
  latitude DECIMAL(9,6), longitude DECIMAL(9,6),
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE vessels (
  vessel_id INT AUTO_INCREMENT PRIMARY KEY,
  vessel_name VARCHAR(100) NOT NULL,
  imo_number VARCHAR(15) UNIQUE,
  owner_company_id INT NULL,
  capacity_teu INT NOT NULL,
  status ENUM('ACTIVE','MAINTENANCE') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_vessel_owner FOREIGN KEY(owner_company_id) REFERENCES companies(company_id) ON DELETE RESTRICT,
  CHECK(capacity_teu > 0)
) ENGINE=InnoDB;

-- ============================================================================
-- FR3 - CONTAINER INVENTORY AND PRICING
-- ============================================================================
CREATE TABLE containers (
  container_id INT AUTO_INCREMENT PRIMARY KEY,
  container_number VARCHAR(15) NOT NULL UNIQUE,
  seller_id INT NOT NULL,
  container_type ENUM('DRY','REEFER','OPEN_TOP','TANK') NOT NULL,
  size_ft TINYINT NOT NULL,
  max_weight_kg DECIMAL(12,2) NOT NULL,
  max_volume_cbm DECIMAL(10,3) NOT NULL,
  current_port_id INT NOT NULL,
  status ENUM('AVAILABLE','ALLOCATED','IN_TRANSIT','MAINTENANCE') NOT NULL DEFAULT 'AVAILABLE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_container_seller FOREIGN KEY(seller_id) REFERENCES companies(company_id) ON DELETE RESTRICT,
  CONSTRAINT fk_container_port FOREIGN KEY(current_port_id) REFERENCES ports(port_id) ON DELETE RESTRICT,
  CHECK(max_weight_kg > 0 AND max_volume_cbm > 0),
  INDEX idx_container_search(seller_id,current_port_id,status,container_type)
) ENGINE=InnoDB;

CREATE TABLE pricing_rules (
  rule_id INT AUTO_INCREMENT PRIMARY KEY,
  seller_id INT NOT NULL,
  origin_port_id INT NOT NULL, dest_port_id INT NOT NULL,
  container_type ENUM('DRY','REEFER','OPEN_TOP','TANK') NOT NULL,
  base_rate DECIMAL(14,2) NOT NULL,
  rate_per_kg DECIMAL(10,4) NOT NULL DEFAULT 0,
  rate_per_cbm DECIMAL(10,4) NOT NULL DEFAULT 0,
  handling_rate DECIMAL(12,2) NOT NULL DEFAULT 0,
  customs_rate DECIMAL(7,4) NOT NULL DEFAULT 0,
  tax_rate DECIMAL(7,4) NOT NULL DEFAULT 0,
  insurance_rate DECIMAL(7,4) NOT NULL DEFAULT 0,
  season_multiplier DECIMAL(6,3) NOT NULL DEFAULT 1.000,
  demand_multiplier DECIMAL(6,3) NOT NULL DEFAULT 1.000,
  valid_from DATE NOT NULL, valid_to DATE NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_price_seller FOREIGN KEY(seller_id) REFERENCES companies(company_id) ON DELETE RESTRICT,
  CONSTRAINT fk_price_origin FOREIGN KEY(origin_port_id) REFERENCES ports(port_id) ON DELETE RESTRICT,
  CONSTRAINT fk_price_dest FOREIGN KEY(dest_port_id) REFERENCES ports(port_id) ON DELETE RESTRICT,
  CHECK(origin_port_id <> dest_port_id),
  CHECK(base_rate >= 0 AND rate_per_kg >= 0 AND rate_per_cbm >= 0),
  CHECK(season_multiplier > 0 AND demand_multiplier > 0),
  INDEX idx_pricing_lookup(seller_id,origin_port_id,dest_port_id,container_type,is_active)
) ENGINE=InnoDB;

CREATE TABLE pricing_audit (
  audit_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  rule_id INT NOT NULL, changed_by INT NULL,
  old_values JSON NULL, new_values JSON NULL,
  changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_price_audit_rule FOREIGN KEY(rule_id) REFERENCES pricing_rules(rule_id) ON DELETE RESTRICT,
  CONSTRAINT fk_price_audit_user FOREIGN KEY(changed_by) REFERENCES users(user_id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ============================================================================
-- FR4 - PRODUCTS, STOCK, RESERVATIONS, INVENTORY LEDGER
-- quantity = physical on-hand; reserved_qty = booked quantity; available = quantity-reserved.
-- ============================================================================
CREATE TABLE products (
  product_id INT AUTO_INCREMENT PRIMARY KEY,
  sku VARCHAR(40) NOT NULL UNIQUE,
  product_name VARCHAR(120) NOT NULL,
  category VARCHAR(60), hs_code VARCHAR(12), unit VARCHAR(10) NOT NULL DEFAULT 'PCS',
  unit_weight_kg DECIMAL(10,3) NOT NULL DEFAULT 0,
  unit_volume_cbm DECIMAL(10,4) NOT NULL DEFAULT 0,
  unit_price DECIMAL(14,2) NOT NULL,
  owner_company_id INT NOT NULL,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_product_owner FOREIGN KEY(owner_company_id) REFERENCES companies(company_id) ON DELETE RESTRICT,
  CHECK(unit_weight_kg >= 0 AND unit_volume_cbm >= 0 AND unit_price >= 0),
  INDEX idx_product_search(owner_company_id,product_name,sku)
) ENGINE=InnoDB;

CREATE TABLE stock (
  stock_id INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT NOT NULL,
  quantity INT NOT NULL DEFAULT 0,
  reserved_qty INT NOT NULL DEFAULT 0,
  damaged_qty INT NOT NULL DEFAULT 0,
  last_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT uq_stock_product UNIQUE(product_id),
  CONSTRAINT fk_stock_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE RESTRICT,
  CHECK(quantity >= 0 AND reserved_qty >= 0 AND damaged_qty >= 0 AND reserved_qty <= quantity),
  INDEX idx_stock_available(quantity,reserved_qty)
) ENGINE=InnoDB;

CREATE TABLE inventory_ledger (
  ledger_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  stock_id INT NOT NULL, product_id INT NOT NULL,
  txn_type ENUM('IN','OUT','DAMAGE','ADJUST','CLAIM_LOSS') NOT NULL,
  quantity INT NOT NULL,
  balance_after INT NOT NULL,
  reference_type VARCHAR(30), reference_id BIGINT,
  remarks VARCHAR(255), created_by INT NULL,
  txn_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ledger_stock FOREIGN KEY(stock_id) REFERENCES stock(stock_id) ON DELETE RESTRICT,
  CONSTRAINT fk_ledger_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE RESTRICT,
  CONSTRAINT fk_ledger_user FOREIGN KEY(created_by) REFERENCES users(user_id) ON DELETE SET NULL,
  CHECK(quantity > 0), INDEX idx_ledger_product_time(product_id,txn_time)
) ENGINE=InnoDB;

-- ============================================================================
-- FR2 - SHIPMENTS, SHIPMENT ITEMS AND MOVEMENT EVENTS
-- ============================================================================
CREATE TABLE shipment (
  shipment_id INT AUTO_INCREMENT PRIMARY KEY,
  shipment_no VARCHAR(25) NOT NULL UNIQUE,
  consumer_id INT NOT NULL, seller_id INT NOT NULL,
  container_id INT NOT NULL, vessel_id INT NULL,
  origin_port_id INT NOT NULL, dest_port_id INT NOT NULL,
  cargo_description VARCHAR(255), cargo_weight_kg DECIMAL(12,2) NOT NULL DEFAULT 0,
  cargo_volume_cbm DECIMAL(10,3) NOT NULL DEFAULT 0,
  quoted_price DECIMAL(14,2) NOT NULL DEFAULT 0,
  status ENUM('BOOKED','LOADED','DEPARTED','IN_TRANSIT','ARRIVED','CUSTOMS_CLEARED','DELIVERED','CANCELLED') NOT NULL DEFAULT 'BOOKED',
  etd DATE, eta DATE, actual_arrival DATE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_shipment_consumer FOREIGN KEY(consumer_id) REFERENCES customers(customer_id) ON DELETE RESTRICT,
  CONSTRAINT fk_shipment_seller FOREIGN KEY(seller_id) REFERENCES companies(company_id) ON DELETE RESTRICT,
  CONSTRAINT fk_shipment_container FOREIGN KEY(container_id) REFERENCES containers(container_id) ON DELETE RESTRICT,
  CONSTRAINT fk_shipment_vessel FOREIGN KEY(vessel_id) REFERENCES vessels(vessel_id) ON DELETE RESTRICT,
  CONSTRAINT fk_shipment_origin FOREIGN KEY(origin_port_id) REFERENCES ports(port_id) ON DELETE RESTRICT,
  CONSTRAINT fk_shipment_dest FOREIGN KEY(dest_port_id) REFERENCES ports(port_id) ON DELETE RESTRICT,
  CHECK(origin_port_id <> dest_port_id AND cargo_weight_kg >= 0 AND cargo_volume_cbm >= 0),
  INDEX idx_shipment_consumer(consumer_id,created_at),
  INDEX idx_shipment_seller(seller_id,status),
  INDEX idx_shipment_search(shipment_no,status,container_id)
) ENGINE=InnoDB;

CREATE TABLE shipment_items (
  item_id INT AUTO_INCREMENT PRIMARY KEY,
  shipment_id INT NOT NULL, product_id INT NOT NULL,
  quantity INT NOT NULL, unit_price DECIMAL(14,2) NOT NULL,
  weight_kg DECIMAL(12,2) NOT NULL, volume_cbm DECIMAL(10,3) NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  CONSTRAINT fk_shipment_item_shipment FOREIGN KEY(shipment_id) REFERENCES shipment(shipment_id) ON DELETE RESTRICT,
  CONSTRAINT fk_shipment_item_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE RESTRICT,
  CHECK(quantity > 0 AND unit_price >= 0 AND weight_kg >= 0 AND volume_cbm >= 0 AND amount >= 0),
  INDEX idx_shipment_items_shipment(shipment_id)
) ENGINE=InnoDB;

CREATE TABLE container_movements (
  movement_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  shipment_id INT NOT NULL, container_id INT NOT NULL,
  status ENUM('BOOKED','LOADED','DEPARTED','IN_TRANSIT','ARRIVED','CUSTOMS_CLEARED','DELIVERED','CANCELLED') NOT NULL,
  port_id INT NULL, location_text VARCHAR(180), event_time DATETIME NOT NULL,
  remarks VARCHAR(255), updated_by INT NULL,
  CONSTRAINT fk_movement_shipment FOREIGN KEY(shipment_id) REFERENCES shipment(shipment_id) ON DELETE RESTRICT,
  CONSTRAINT fk_movement_container FOREIGN KEY(container_id) REFERENCES containers(container_id) ON DELETE RESTRICT,
  CONSTRAINT fk_movement_port FOREIGN KEY(port_id) REFERENCES ports(port_id) ON DELETE SET NULL,
  CONSTRAINT fk_movement_user FOREIGN KEY(updated_by) REFERENCES users(user_id) ON DELETE SET NULL,
  INDEX idx_movement_timeline(shipment_id,event_time)
) ENGINE=InnoDB;

-- ============================================================================
-- FR5 - INVOICES, LINE ITEMS AND MANUALLY RECORDED PAYMENTS (NO GATEWAY)
-- ============================================================================
CREATE TABLE billing_invoices (
  invoice_id INT AUTO_INCREMENT PRIMARY KEY,
  invoice_no VARCHAR(25) NOT NULL UNIQUE,
  shipment_id INT NOT NULL UNIQUE,
  consumer_id INT NOT NULL, seller_id INT NOT NULL,
  sub_total DECIMAL(14,2) NOT NULL DEFAULT 0,
  tax_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  total_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  paid_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  status ENUM('UNPAID','PARTIAL','PAID','VOID') NOT NULL DEFAULT 'UNPAID',
  issue_date DATE NOT NULL, due_date DATE NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_invoice_shipment FOREIGN KEY(shipment_id) REFERENCES shipment(shipment_id) ON DELETE RESTRICT,
  CONSTRAINT fk_invoice_consumer FOREIGN KEY(consumer_id) REFERENCES customers(customer_id) ON DELETE RESTRICT,
  CONSTRAINT fk_invoice_seller FOREIGN KEY(seller_id) REFERENCES companies(company_id) ON DELETE RESTRICT,
  CHECK(sub_total >= 0 AND tax_amount >= 0 AND total_amount >= 0 AND paid_amount >= 0 AND paid_amount <= total_amount),
  INDEX idx_invoice_status(status,due_date), INDEX idx_invoice_consumer(consumer_id)
) ENGINE=InnoDB;

CREATE TABLE invoice_line_items (
  item_id INT AUTO_INCREMENT PRIMARY KEY,
  invoice_id INT NOT NULL,
  item_type ENUM('FREIGHT','HANDLING','CUSTOMS','TAX','INSURANCE','OTHER') NOT NULL,
  description VARCHAR(180), quantity DECIMAL(10,2) NOT NULL DEFAULT 1,
  unit_price DECIMAL(14,2) NOT NULL, amount DECIMAL(14,2) NOT NULL,
  CONSTRAINT fk_invoice_item_invoice FOREIGN KEY(invoice_id) REFERENCES billing_invoices(invoice_id) ON DELETE RESTRICT,
  CHECK(quantity >= 0 AND unit_price >= 0 AND amount >= 0)
) ENGINE=InnoDB;

CREATE TABLE payments (
  payment_id INT AUTO_INCREMENT PRIMARY KEY,
  invoice_id INT NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  payment_mode ENUM('BANK','UPI','CHEQUE','CASH','OTHER') NOT NULL,
  reference_no VARCHAR(60), payment_date DATE NOT NULL,
  recorded_by INT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_payment_invoice FOREIGN KEY(invoice_id) REFERENCES billing_invoices(invoice_id) ON DELETE RESTRICT,
  CONSTRAINT fk_payment_user FOREIGN KEY(recorded_by) REFERENCES users(user_id) ON DELETE SET NULL,
  CHECK(amount > 0), INDEX idx_payment_invoice(invoice_id,payment_date)
) ENGINE=InnoDB;

-- ============================================================================
-- FR2 - PROFIT & LOSS. net_profit is generated by MySQL; never insert it directly.
-- Revenue is recognized from paid invoice amounts. Costs are maintained by seller/admin.
-- ============================================================================
CREATE TABLE profit_loss (
  pl_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  shipment_id INT NULL, seller_id INT NOT NULL,
  period_month DATE NOT NULL,
  revenue DECIMAL(14,2) NOT NULL DEFAULT 0,
  freight_cost DECIMAL(14,2) NOT NULL DEFAULT 0,
  port_cost DECIMAL(14,2) NOT NULL DEFAULT 0,
  handling_cost DECIMAL(14,2) NOT NULL DEFAULT 0,
  claim_loss DECIMAL(14,2) NOT NULL DEFAULT 0,
  net_profit DECIMAL(14,2) GENERATED ALWAYS AS (revenue-freight_cost-port_cost-handling_cost-claim_loss) STORED,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_pl_shipment FOREIGN KEY(shipment_id) REFERENCES shipment(shipment_id) ON DELETE RESTRICT,
  CONSTRAINT fk_pl_seller FOREIGN KEY(seller_id) REFERENCES companies(company_id) ON DELETE RESTRICT,
  UNIQUE KEY uq_pl_shipment(shipment_id), INDEX idx_pl_seller_month(seller_id,period_month)
) ENGINE=InnoDB;

-- ============================================================================
-- FR7 - CLAIMS, EVIDENCE, STATUS HISTORY AND COMMENTS
-- ============================================================================
CREATE TABLE claims (
  claim_id INT AUTO_INCREMENT PRIMARY KEY,
  claim_no VARCHAR(25) NOT NULL UNIQUE,
  shipment_id INT NOT NULL, container_id INT NOT NULL, consumer_id INT NOT NULL,
  claim_type ENUM('LOSS','DAMAGE','DELAY','SHORTAGE') NOT NULL,
  product_id INT NULL, affected_quantity INT NOT NULL DEFAULT 0,
  description TEXT NOT NULL,
  claimed_amount DECIMAL(14,2) NOT NULL,
  approved_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  settled_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  status ENUM('SUBMITTED','UNDER_REVIEW','APPROVED','PARTIALLY_APPROVED','REJECTED','SETTLED','CANCELLED') NOT NULL DEFAULT 'SUBMITTED',
  seller_remarks VARCHAR(500), raised_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  settled_at DATETIME NULL,
  CONSTRAINT fk_claim_shipment FOREIGN KEY(shipment_id) REFERENCES shipment(shipment_id) ON DELETE RESTRICT,
  CONSTRAINT fk_claim_container FOREIGN KEY(container_id) REFERENCES containers(container_id) ON DELETE RESTRICT,
  CONSTRAINT fk_claim_consumer FOREIGN KEY(consumer_id) REFERENCES customers(customer_id) ON DELETE RESTRICT,
  CONSTRAINT fk_claim_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE RESTRICT,
  CHECK(affected_quantity >= 0),
  CHECK(claimed_amount >= 0 AND approved_amount >= 0 AND settled_amount >= 0),
  INDEX idx_claim_status(status,raised_at), INDEX idx_claim_shipment(shipment_id)
) ENGINE=InnoDB;

CREATE TABLE claim_documents (
  document_id INT AUTO_INCREMENT PRIMARY KEY,
  claim_id INT NOT NULL, file_name VARCHAR(180) NOT NULL,
  file_path VARCHAR(500) NOT NULL,
  file_type ENUM('PDF','JPG','JPEG','PNG') NOT NULL,
  file_size_bytes BIGINT NOT NULL,
  uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_claim_doc_claim FOREIGN KEY(claim_id) REFERENCES claims(claim_id) ON DELETE RESTRICT,
  CHECK(file_size_bytes > 0 AND file_size_bytes <= 10485760)
) ENGINE=InnoDB;

CREATE TABLE claim_status_history (
  history_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  claim_id INT NOT NULL, old_status VARCHAR(30), new_status VARCHAR(30) NOT NULL,
  changed_by INT NULL, remarks VARCHAR(500), changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_claim_history_claim FOREIGN KEY(claim_id) REFERENCES claims(claim_id) ON DELETE RESTRICT,
  CONSTRAINT fk_claim_history_user FOREIGN KEY(changed_by) REFERENCES users(user_id) ON DELETE SET NULL,
  INDEX idx_claim_history(claim_id,changed_at)
) ENGINE=InnoDB;

CREATE TABLE claim_comments (
  comment_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  claim_id INT NOT NULL, user_id INT NOT NULL,
  comment_text VARCHAR(2000) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_claim_comment_claim FOREIGN KEY(claim_id) REFERENCES claims(claim_id) ON DELETE RESTRICT,
  CONSTRAINT fk_claim_comment_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- ============================================================================
-- FR6 - CACHED ANALYTICS TABLES + AI REQUEST/RESPONSE AUDIT
-- ============================================================================
CREATE TABLE abc_classification_result (
  result_id BIGINT AUTO_INCREMENT PRIMARY KEY, product_id INT NOT NULL,
  annual_value DECIMAL(16,2) NOT NULL DEFAULT 0,
  cumulative_pct DECIMAL(6,2) NOT NULL DEFAULT 0,
  abc_class ENUM('A','B','C') NOT NULL,
  calculated_on DATE NOT NULL,
  CONSTRAINT fk_abc_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE RESTRICT,
  UNIQUE KEY uq_abc_product_date(product_id,calculated_on)
) ENGINE=InnoDB;

CREATE TABLE inventory_turnover_result (
  result_id BIGINT AUTO_INCREMENT PRIMARY KEY, product_id INT NOT NULL,
  period_start DATE NOT NULL, period_end DATE NOT NULL,
  cogs DECIMAL(16,2) NOT NULL DEFAULT 0,
  avg_inventory DECIMAL(16,2) NOT NULL DEFAULT 0,
  turnover_ratio DECIMAL(12,4) NOT NULL DEFAULT 0,
  calculated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_turnover_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE RESTRICT,
  CHECK(period_end >= period_start), INDEX idx_turnover_period(period_start,period_end)
) ENGINE=InnoDB;

CREATE TABLE profitability_result (
  result_id BIGINT AUTO_INCREMENT PRIMARY KEY, product_id INT NOT NULL,
  period_month DATE NOT NULL, revenue DECIMAL(16,2) NOT NULL DEFAULT 0,
  cost DECIMAL(16,2) NOT NULL DEFAULT 0, margin_pct DECIMAL(8,2) NOT NULL DEFAULT 0,
  calculated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_profitability_product FOREIGN KEY(product_id) REFERENCES products(product_id) ON DELETE RESTRICT,
  UNIQUE KEY uq_profit_product_month(product_id,period_month)
) ENGINE=InnoDB;

CREATE TABLE sales_trend_result (
  result_id BIGINT AUTO_INCREMENT PRIMARY KEY, period_month DATE NOT NULL,
  origin_port_id INT NULL, dest_port_id INT NULL,
  total_sales DECIMAL(16,2) NOT NULL DEFAULT 0, total_qty BIGINT NOT NULL DEFAULT 0,
  growth_pct DECIMAL(8,2) NULL, calculated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_trend_origin FOREIGN KEY(origin_port_id) REFERENCES ports(port_id) ON DELETE SET NULL,
  CONSTRAINT fk_trend_dest FOREIGN KEY(dest_port_id) REFERENCES ports(port_id) ON DELETE SET NULL,
  INDEX idx_trend_month(period_month)
) ENGINE=InnoDB;

CREATE TABLE demand_forecast (
  forecast_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  origin_port_id INT NOT NULL, dest_port_id INT NOT NULL,
  container_type ENUM('DRY','REEFER','OPEN_TOP','TANK') NOT NULL,
  forecast_month DATE NOT NULL, predicted_bookings INT NOT NULL DEFAULT 0,
  confidence_pct DECIMAL(5,2), suggested_multiplier DECIMAL(6,3),
  generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_forecast_origin FOREIGN KEY(origin_port_id) REFERENCES ports(port_id) ON DELETE RESTRICT,
  CONSTRAINT fk_forecast_dest FOREIGN KEY(dest_port_id) REFERENCES ports(port_id) ON DELETE RESTRICT,
  UNIQUE KEY uq_forecast_route_month(origin_port_id,dest_port_id,container_type,forecast_month)
) ENGINE=InnoDB;

CREATE TABLE ai_interaction_log (
  ai_log_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NULL, feature ENUM('SHIPMENT_ASSISTANT','CLAIM_SUMMARY','QUOTE_EXPLANATION','SMART_SEARCH','REPORT_SUMMARY') NOT NULL,
  request_summary TEXT NOT NULL, response_summary TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ai_user FOREIGN KEY(user_id) REFERENCES users(user_id) ON DELETE SET NULL,
  INDEX idx_ai_user_date(user_id,created_at)
