-- Ledger quantity convention: ADJUST uses signed quantity; other types use positive quantity.
CREATE TRIGGER trg_ledger_validate_bi BEFORE INSERT ON inventory_ledger
FOR EACH ROW
BEGIN
  DECLARE v_qty INT;
  DECLARE v_product INT;
  DECLARE v_new_balance INT;
  SELECT quantity,product_id INTO v_qty,v_product FROM stock WHERE stock_id=NEW.stock_id FOR UPDATE;
  IF v_product <> NEW.product_id THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Ledger product does not match stock record';
  END IF;
  IF NEW.txn_type='ADJUST' THEN
    SET v_new_balance=v_qty+NEW.quantity;
  ELSEIF NEW.txn_type IN ('IN') THEN
    SET v_new_balance=v_qty+NEW.quantity;
  ELSE
    SET v_new_balance=v_qty-NEW.quantity;
  END IF;
  IF NEW.quantity=0 OR v_new_balance < 0 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Invalid ledger quantity or insufficient stock';
  END IF;
  IF NEW.txn_type IN ('OUT','DAMAGE','CLAIM_LOSS') AND (v_qty-NEW.quantity) < (SELECT reserved_qty FROM stock WHERE stock_id=NEW.stock_id) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Cannot issue stock already reserved for shipments';
  END IF;
  SET NEW.balance_after=v_new_balance;
END$$

CREATE TRIGGER trg_ledger_apply_ai AFTER INSERT ON inventory_ledger
FOR EACH ROW
BEGIN
  UPDATE stock SET quantity=NEW.balance_after,
    damaged_qty=damaged_qty + IF(NEW.txn_type='DAMAGE',NEW.quantity,0)
    WHERE stock_id=NEW.stock_id;
END$$

