-- FR7: submit claim; only arrived/delivered shipments and within configurable claim days.
CREATE PROCEDURE sp_submit_claim(
  IN p_claim_no VARCHAR(25), IN p_shipment_id INT, IN p_customer_id INT,
  IN p_claim_type VARCHAR(20), IN p_product_id INT, IN p_affected_quantity INT,
  IN p_description TEXT, IN p_claimed_amount DECIMAL(14,2), IN p_claim_window_days INT
)
BEGIN
  DECLARE v_status VARCHAR(30); DECLARE v_container_id INT; DECLARE v_consumer_id INT;
  SELECT status,container_id,consumer_id INTO v_status,v_container_id,v_consumer_id
    FROM shipment WHERE shipment_id=p_shipment_id;
  IF v_status IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Shipment not found'; END IF;
  IF v_status NOT IN ('ARRIVED','CUSTOMS_CLEARED','DELIVERED') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Claims are allowed only after arrival';
  END IF;
  IF v_consumer_id<>p_customer_id THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Customer does not own this shipment'; END IF;
  IF p_claim_window_days<0 OR DATEDIFF(CURDATE(),(SELECT COALESCE(actual_arrival,eta) FROM shipment WHERE shipment_id=p_shipment_id))>p_claim_window_days THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Claim window has expired';
  END IF;
  IF p_affected_quantity < 0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Affected quantity cannot be negative'; END IF;
  INSERT INTO claims(claim_no,shipment_id,container_id,consumer_id,claim_type,product_id,affected_quantity,description,claimed_amount)
  VALUES(p_claim_no,p_shipment_id,v_container_id,p_customer_id,p_claim_type,p_product_id,p_affected_quantity,p_description,p_claimed_amount);
  SELECT LAST_INSERT_ID() AS claim_id;
END$$

-- FR7: seller decision. Approved amount must be between zero and claimed amount.
CREATE PROCEDURE sp_review_claim(
  IN p_claim_id INT, IN p_decision VARCHAR(30), IN p_approved_amount DECIMAL(14,2),
  IN p_reason VARCHAR(500), IN p_user_id INT
)
BEGIN
  DECLARE v_claimed DECIMAL(14,2); DECLARE v_status VARCHAR(30);
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  START TRANSACTION;
  SELECT claimed_amount,status INTO v_claimed,v_status FROM claims WHERE claim_id=p_claim_id FOR UPDATE;
  IF v_status IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Claim not found'; END IF;
  IF v_status NOT IN ('SUBMITTED','UNDER_REVIEW') THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Claim is not reviewable'; END IF;
  IF p_decision NOT IN ('APPROVED','PARTIALLY_APPROVED','REJECTED') OR p_approved_amount<0 OR p_approved_amount>v_claimed THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Invalid claim decision or approved amount';
  END IF;
  IF p_decision='APPROVED' AND p_approved_amount<>v_claimed THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Full approval must equal claimed amount'; END IF;
  IF p_decision='PARTIALLY_APPROVED' AND (p_approved_amount<=0 OR p_approved_amount>=v_claimed) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Partial approval must be between zero and claimed amount'; END IF;
  SET @app_user_id=p_user_id;
  UPDATE claims SET status=p_decision,approved_amount=p_approved_amount,seller_remarks=p_reason WHERE claim_id=p_claim_id;
  SET @app_user_id=NULL;
  COMMIT;
  SELECT * FROM claims WHERE claim_id=p_claim_id;
END$$

-- FR7: settle approved claim exactly once; trigger posts settlement to P&L.
CREATE PROCEDURE sp_settle_claim(
  IN p_claim_id INT, IN p_settlement_amount DECIMAL(14,2), IN p_user_id INT
)
BEGIN
  DECLARE v_status VARCHAR(30); DECLARE v_approved DECIMAL(14,2);
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN SET @app_user_id=NULL; ROLLBACK; RESIGNAL; END;
  START TRANSACTION;
  SELECT status,approved_amount INTO v_status,v_approved FROM claims WHERE claim_id=p_claim_id FOR UPDATE;
  IF v_status IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Claim not found'; END IF;
  IF v_status NOT IN ('APPROVED','PARTIALLY_APPROVED') THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Claim is not approved for settlement'; END IF;
  IF p_settlement_amount<=0 OR p_settlement_amount>v_approved THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Invalid settlement amount'; END IF;
  SET @app_user_id=p_user_id;
  UPDATE claims SET status='SETTLED',settled_amount=p_settlement_amount,settled_at=NOW() WHERE claim_id=p_claim_id;
  SET @app_user_id=NULL;
  COMMIT;
  SELECT * FROM claims WHERE claim_id=p_claim_id;
END$$

-- FR2: refresh shipment P&L from invoice paid amount and manually maintained costs.
CREATE PROCEDURE sp_refresh_shipment_pl(IN p_shipment_id INT)
BEGIN
  DECLARE v_seller INT; DECLARE v_revenue DECIMAL(14,2); DECLARE v_claim_loss DECIMAL(14,2);
  SELECT seller_id INTO v_seller FROM shipment WHERE shipment_id=p_shipment_id;
  IF v_seller IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Shipment not found'; END IF;
  SELECT COALESCE(paid_amount,0) INTO v_revenue FROM billing_invoices WHERE shipment_id=p_shipment_id;
  SELECT COALESCE(SUM(settled_amount),0) INTO v_claim_loss FROM claims WHERE shipment_id=p_shipment_id AND status='SETTLED';
  INSERT INTO profit_loss(shipment_id,seller_id,period_month,revenue,claim_loss)
  VALUES(p_shipment_id,v_seller,STR_TO_DATE(DATE_FORMAT(CURDATE(),'%Y-%m-01'),'%Y-%m-%d'),v_revenue,v_claim_loss)
  ON DUPLICATE KEY UPDATE revenue=VALUES(revenue),claim_loss=VALUES(claim_loss);
END$$

-- FR6: ABC classification from completed shipment sales value in the requested period.
CREATE PROCEDURE sp_calculate_abc(IN p_start DATE, IN p_end DATE)
BEGIN
  DELETE FROM abc_classification_result WHERE calculated_on=CURDATE();
  INSERT INTO abc_classification_result(product_id,annual_value,cumulative_pct,abc_class,calculated_on)
  SELECT product_id,annual_value,cumulative_pct,
    CASE WHEN cumulative_pct<=80 THEN 'A' WHEN cumulative_pct<=95 THEN 'B' ELSE 'C' END,CURDATE()
  FROM (
    SELECT product_id,annual_value,
      ROUND(100*SUM(annual_value) OVER(ORDER BY annual_value DESC ROWS UNBOUNDED PRECEDING)/NULLIF(SUM(annual_value) OVER(),0),2) cumulative_pct
    FROM (SELECT si.product_id,SUM(si.amount) annual_value
      FROM shipment_items si JOIN shipment s ON s.shipment_id=si.shipment_id
      WHERE s.status='DELIVERED' AND DATE(s.created_at) BETWEEN p_start AND p_end
      GROUP BY si.product_id) x
  ) ranked;
  SELECT * FROM abc_classification_result WHERE calculated_on=CURDATE();
END$$

-- FR6: monthly product revenue/cost margin. Cost proxy is product unit price * shipped qty.
CREATE PROCEDURE sp_calculate_profitability(IN p_month DATE)
BEGIN
  INSERT INTO profitability_result(product_id,period_month,revenue,cost,margin_pct)
  SELECT si.product_id,STR_TO_DATE(DATE_FORMAT(p_month,'%Y-%m-01'),'%Y-%m-%d'),SUM(si.amount),
    SUM(si.quantity*p.unit_price),
    CASE WHEN SUM(si.amount)=0 THEN 0 ELSE ROUND((SUM(si.amount)-SUM(si.quantity*p.unit_price))/SUM(si.amount)*100,2) END
  FROM shipment_items si JOIN shipment s ON s.shipment_id=si.shipment_id JOIN products p ON p.product_id=si.product_id
  WHERE s.status='DELIVERED' AND DATE_FORMAT(s.created_at,'%Y-%m')=DATE_FORMAT(p_month,'%Y-%m')
  GROUP BY si.product_id
  ON DUPLICATE KEY UPDATE revenue=VALUES(revenue),cost=VALUES(cost),margin_pct=VALUES(margin_pct);
  SELECT * FROM profitability_result WHERE period_month=STR_TO_DATE(DATE_FORMAT(p_month,'%Y-%m-01'),'%Y-%m-%d');
END$$

-- FR6: sales trend by month and route. Revenue proxy uses invoice paid amount.
CREATE PROCEDURE sp_calculate_sales_trend(IN p_start DATE, IN p_end DATE)
BEGIN
  DELETE FROM sales_trend_result WHERE period_month BETWEEN STR_TO_DATE(DATE_FORMAT(p_start,'%Y-%m-01'),'%Y-%m-%d') AND STR_TO_DATE(DATE_FORMAT(p_end,'%Y-%m-01'),'%Y-%m-%d');
  INSERT INTO sales_trend_result(period_month,origin_port_id,dest_port_id,total_sales,total_qty)
  SELECT STR_TO_DATE(DATE_FORMAT(s.created_at,'%Y-%m-01'),'%Y-%m-%d'),s.origin_port_id,s.dest_port_id,
    SUM(COALESCE(i.paid_amount,0)),SUM(si.quantity)
  FROM shipment s LEFT JOIN billing_invoices i ON i.shipment_id=s.shipment_id
  LEFT JOIN shipment_items si ON si.shipment_id=s.shipment_id
  WHERE DATE(s.created_at) BETWEEN p_start AND p_end
  GROUP BY DATE_FORMAT(s.created_at,'%Y-%m'),s.origin_port_id,s.dest_port_id;
  SELECT * FROM sales_trend_result ORDER BY period_month,origin_port_id,dest_port_id;
END$$

-- FR6: turnover ratio for a product/date range. Uses cost of delivered goods / average current inventory value proxy.
CREATE PROCEDURE sp_calculate_inventory_turnover(IN p_product_id INT, IN p_start DATE, IN p_end DATE)
BEGIN
  DECLARE v_cogs DECIMAL(16,2); DECLARE v_avg DECIMAL(16,2);
  SELECT COALESCE(SUM(si.quantity*p.unit_price),0) INTO v_cogs
  FROM shipment_items si JOIN shipment s ON s.shipment_id=si.shipment_id JOIN products p ON p.product_id=si.product_id
  WHERE si.product_id=p_product_id AND s.status='DELIVERED' AND DATE(s.created_at) BETWEEN p_start AND p_end;
  SELECT COALESCE(st.quantity*p.unit_price,0) INTO v_avg FROM stock st JOIN products p ON p.product_id=st.product_id WHERE st.product_id=p_product_id;
  INSERT INTO inventory_turnover_result(product_id,period_start,period_end,cogs,avg_inventory,turnover_ratio)
  VALUES(p_product_id,p_start,p_end,v_cogs,v_avg,IF(v_avg=0,0,ROUND(v_cogs/v_avg,4)));
  SELECT * FROM inventory_turnover_result WHERE product_id=p_product_id ORDER BY result_id DESC LIMIT 1;
END$$

-- FR6: dashboard KPI summary (date range).
CREATE PROCEDURE sp_dashboard_kpis(IN p_start DATE, IN p_end DATE)
BEGIN
  SELECT
    (SELECT COUNT(*) FROM shipment WHERE status NOT IN ('DELIVERED','CANCELLED')) AS active_shipments,
    (SELECT COUNT(*) FROM containers WHERE status='AVAILABLE') AS available_containers,
    (SELECT COALESCE(SUM(paid_amount),0) FROM billing_invoices WHERE issue_date BETWEEN p_start AND p_end) AS revenue_received,
    (SELECT COUNT(*) FROM billing_invoices WHERE status IN ('UNPAID','PARTIAL')) AS pending_invoices,
    (SELECT COUNT(*) FROM claims WHERE status NOT IN ('SETTLED','REJECTED','CANCELLED')) AS open_claims;
END$$

