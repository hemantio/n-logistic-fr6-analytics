CREATE OR REPLACE VIEW vw_shipment_tracking AS
SELECT s.shipment_id,s.shipment_no,s.status,s.etd,s.eta,s.actual_arrival,
       c.container_number,op.port_name AS origin_port,dp.port_name AS destination_port,
       co.company_name AS seller_company,cu.company_name AS consumer_company
FROM shipment s JOIN containers c ON c.container_id=s.container_id
JOIN ports op ON op.port_id=s.origin_port_id JOIN ports dp ON dp.port_id=s.dest_port_id
JOIN companies co ON co.company_id=s.seller_id JOIN customers cust ON cust.customer_id=s.consumer_id
JOIN companies cu ON cu.company_id=cust.company_id;

CREATE OR REPLACE VIEW vw_invoice_balances AS
SELECT invoice_id,invoice_no,shipment_id,consumer_id,seller_id,total_amount,paid_amount,
       total_amount-paid_amount AS balance_due,status,issue_date,due_date
FROM billing_invoices;

CREATE OR REPLACE VIEW vw_stock_availability AS
SELECT st.stock_id,p.product_id,p.sku,p.product_name,p.owner_company_id,
       st.quantity,st.reserved_qty,(st.quantity-st.reserved_qty) AS available_qty,
       st.damaged_qty,p.unit_price,(st.quantity-st.reserved_qty)*p.unit_price AS available_stock_value
FROM stock st JOIN products p ON p.product_id=st.product_id;

CREATE OR REPLACE VIEW vw_profit_loss_monthly AS
SELECT seller_id,period_month,SUM(revenue) revenue,SUM(freight_cost) freight_cost,
       SUM(port_cost) port_cost,SUM(handling_cost) handling_cost,SUM(claim_loss) claim_loss,
       SUM(net_profit) net_profit
FROM profit_loss GROUP BY seller_id,period_month;

