    SELECT s.shipment_id,s.seller_id,STR_TO_DATE(DATE_FORMAT(CURDATE(),'%Y-%m-01'),'%Y-%m-%d'),0,0,0,0,NEW.settled_amount
    FROM shipment s WHERE s.shipment_id=NEW.shipment_id
    ON DUPLICATE KEY UPDATE claim_loss=claim_loss+NEW.settled_amount;
  END IF;
END$$

