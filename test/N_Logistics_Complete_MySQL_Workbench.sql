-- FR3/FR4/FR5: cancel an unshipped booking and release its reserved stock/container.
-- Only bookings that have not departed may be cancelled by this routine.
CREATE PROCEDURE sp_cancel_booking(IN p_shipment_id INT, IN p_user_id INT)
BEGIN
  DECLARE v_status VARCHAR(30);
  DECLARE v_container INT;
  DECLARE v_invoice INT;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN SET @app_user_id=NULL; ROLLBACK; RESIGNAL; END;
  START TRANSACTION;
  SELECT status,container_id INTO v_status,v_container
    FROM shipment WHERE shipment_id=p_shipment_id FOR UPDATE;
  IF v_status IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Shipment not found'; END IF;
  IF v_status NOT IN ('BOOKED','LOADED') THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Only a pre-departure booking can be cancelled'; END IF;
  -- Release every product reservation recorded on this shipment.
  UPDATE stock st JOIN (
    SELECT si.product_id,SUM(si.quantity) qty FROM shipment_items si
    WHERE si.shipment_id=p_shipment_id GROUP BY si.product_id
  ) x ON x.product_id=st.product_id
  SET st.reserved_qty=GREATEST(0,st.reserved_qty-x.qty);
  UPDATE containers SET status='AVAILABLE' WHERE container_id=v_container;
  SELECT invoice_id INTO v_invoice FROM billing_invoices WHERE shipment_id=p_shipment_id LIMIT 1;
  IF v_invoice IS NOT NULL THEN
    UPDATE billing_invoices SET status='VOID' WHERE invoice_id=v_invoice AND paid_amount=0;
    IF EXISTS(SELECT 1 FROM billing_invoices WHERE invoice_id=v_invoice AND paid_amount>0) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Booking has payments; resolve/refund manually before cancellation';
    END IF;
  END IF;
  SET @app_user_id=p_user_id;
  UPDATE shipment SET status='CANCELLED' WHERE shipment_id=p_shipment_id;
  INSERT INTO audit_log(user_id,action,table_name,record_id,new_value)
    VALUES(p_user_id,'BOOKING_CANCELLED','shipment',p_shipment_id,JSON_OBJECT('status','CANCELLED'));
  SET @app_user_id=NULL;
  COMMIT;
  SELECT shipment_id,shipment_no,status FROM shipment WHERE shipment_id=p_shipment_id;
END$$

