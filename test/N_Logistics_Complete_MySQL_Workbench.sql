CREATE TRIGGER trg_claim_settlement_pl_au AFTER UPDATE ON claims
FOR EACH ROW
BEGIN
  DECLARE v_stock_id INT;
  DECLARE v_txn_type VARCHAR(20);
  IF OLD.status <> 'SETTLED' AND NEW.status='SETTLED' THEN
    -- If the claim identifies affected goods, release their reservation and post the loss/damage to the ledger.
    IF NEW.product_id IS NOT NULL AND NEW.affected_quantity > 0 THEN
      SELECT stock_id INTO v_stock_id FROM stock WHERE product_id=NEW.product_id FOR UPDATE;
      UPDATE stock SET reserved_qty=GREATEST(0,reserved_qty-NEW.affected_quantity) WHERE stock_id=v_stock_id;
