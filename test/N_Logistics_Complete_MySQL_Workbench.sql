-- FR3: return a quotation for a route, seller, container type and cargo metrics.
CREATE PROCEDURE sp_calculate_dynamic_price(
  IN p_seller_id INT, IN p_origin INT, IN p_destination INT,
  IN p_container_type VARCHAR(20), IN p_weight DECIMAL(12,2), IN p_volume DECIMAL(10,3)
)
BEGIN
  SELECT r.rule_id,
    ROUND((r.base_rate + p_weight*r.rate_per_kg + p_volume*r.rate_per_cbm)
      * r.season_multiplier * r.demand_multiplier,2) AS freight_amount,
    ROUND(r.handling_rate,2) AS handling_amount,
    ROUND((r.base_rate + p_weight*r.rate_per_kg + p_volume*r.rate_per_cbm)
      * r.season_multiplier * r.demand_multiplier * r.customs_rate/100,2) AS customs_amount,
    ROUND((r.base_rate + p_weight*r.rate_per_kg + p_volume*r.rate_per_cbm)
      * r.season_multiplier * r.demand_multiplier * r.insurance_rate/100,2) AS insurance_amount,
    r.tax_rate,
    ROUND(((r.base_rate + p_weight*r.rate_per_kg + p_volume*r.rate_per_cbm)
      * r.season_multiplier * r.demand_multiplier + r.handling_rate)
      * (1+r.tax_rate/100),2) AS estimated_total
  FROM pricing_rules r
  WHERE r.seller_id=p_seller_id AND r.origin_port_id=p_origin AND r.dest_port_id=p_destination
    AND r.container_type=p_container_type AND r.is_active=TRUE
    AND CURDATE() >= r.valid_from AND (r.valid_to IS NULL OR CURDATE() <= r.valid_to)
  ORDER BY r.valid_from DESC LIMIT 1;
END$$

-- FR4: stock-in / stock-out / damage / positive stock adjustment through ledger. Quantities are positive; ADJUST adds stock.
CREATE PROCEDURE sp_post_stock_transaction(
  IN p_product_id INT, IN p_type VARCHAR(20), IN p_quantity INT,
  IN p_reference_type VARCHAR(30), IN p_reference_id BIGINT,
  IN p_remarks VARCHAR(255), IN p_user_id INT
)
BEGIN
  DECLARE v_stock_id INT;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  START TRANSACTION;
  SELECT stock_id INTO v_stock_id FROM stock WHERE product_id=p_product_id FOR UPDATE;
  IF v_stock_id IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Stock row not found'; END IF;
  IF p_type NOT IN ('IN','OUT','DAMAGE','ADJUST','CLAIM_LOSS') OR p_quantity=0 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Invalid stock transaction';
  END IF;
  INSERT INTO inventory_ledger(stock_id,product_id,txn_type,quantity,balance_after,reference_type,reference_id,remarks,created_by)
  VALUES(v_stock_id,p_product_id,p_type,ABS(p_quantity),0,p_reference_type,p_reference_id,p_remarks,p_user_id);
  COMMIT;
  SELECT * FROM stock WHERE stock_id=v_stock_id;
END$$

-- FR3/FR4/FR5: one-product booking transaction. This creates shipment, reserves stock,
-- allocates a suitable container, creates invoice and line items. It requires a matching price rule.
CREATE PROCEDURE sp_create_booking(
  IN p_shipment_no VARCHAR(25), IN p_customer_id INT, IN p_seller_id INT,
  IN p_product_id INT, IN p_quantity INT,
  IN p_origin_port INT, IN p_dest_port INT,
  IN p_container_type VARCHAR(20), IN p_vessel_id INT,
  IN p_etd DATE, IN p_eta DATE,
  IN p_invoice_no VARCHAR(25), IN p_due_date DATE,
  IN p_user_id INT
)
BEGIN
  DECLARE v_container_id INT;
  DECLARE v_stock_id INT;
  DECLARE v_available INT;
  DECLARE v_weight DECIMAL(12,2);
  DECLARE v_volume DECIMAL(10,3);
  DECLARE v_unit_price DECIMAL(14,2);
  DECLARE v_product_name VARCHAR(120);
  DECLARE v_rule_id INT;
  DECLARE v_base DECIMAL(14,2);
  DECLARE v_kg DECIMAL(10,4);
  DECLARE v_cbm DECIMAL(10,4);
  DECLARE v_handling DECIMAL(12,2);
  DECLARE v_customs DECIMAL(7,4);
  DECLARE v_tax DECIMAL(7,4);
  DECLARE v_insurance DECIMAL(7,4);
  DECLARE v_season DECIMAL(6,3);
  DECLARE v_demand DECIMAL(6,3);
  DECLARE v_freight DECIMAL(14,2);
  DECLARE v_customs_amt DECIMAL(14,2);
  DECLARE v_insurance_amt DECIMAL(14,2);
  DECLARE v_tax_amt DECIMAL(14,2);
  DECLARE v_subtotal DECIMAL(14,2);
  DECLARE v_total DECIMAL(14,2);
  DECLARE v_shipment_id INT;
  DECLARE v_invoice_id INT;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;

  IF p_quantity <= 0 OR p_origin_port=p_dest_port THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Invalid quantity or route'; END IF;
  START TRANSACTION;
  SELECT st.stock_id,st.quantity-st.reserved_qty,pr.unit_weight_kg,pr.unit_volume_cbm,pr.unit_price,pr.product_name
    INTO v_stock_id,v_available,v_weight,v_volume,v_unit_price,v_product_name
    FROM stock st JOIN products pr ON pr.product_id=st.product_id
    WHERE st.product_id=p_product_id AND pr.owner_company_id=p_seller_id AND pr.status='ACTIVE'
    FOR UPDATE;
  IF v_available < p_quantity THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Insufficient available stock'; END IF;
  SET v_weight=v_weight*p_quantity; SET v_volume=v_volume*p_quantity;

  SELECT c.container_id INTO v_container_id
  FROM containers c
  WHERE c.seller_id=p_seller_id AND c.current_port_id=p_origin_port
    AND c.container_type=p_container_type AND c.status='AVAILABLE'
    AND c.max_weight_kg>=v_weight AND c.max_volume_cbm>=v_volume
  ORDER BY c.container_id LIMIT 1 FOR UPDATE;
  IF v_container_id IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='No available container with sufficient capacity at origin port'; END IF;

  SELECT rule_id,base_rate,rate_per_kg,rate_per_cbm,handling_rate,customs_rate,tax_rate,insurance_rate,season_multiplier,demand_multiplier
    INTO v_rule_id,v_base,v_kg,v_cbm,v_handling,v_customs,v_tax,v_insurance,v_season,v_demand
  FROM pricing_rules WHERE seller_id=p_seller_id AND origin_port_id=p_origin AND dest_port_id=p_dest_port
    AND container_type=p_container_type AND is_active=TRUE AND CURDATE()>=valid_from
    AND (valid_to IS NULL OR CURDATE()<=valid_to) ORDER BY valid_from DESC LIMIT 1;
  IF v_rule_id IS NULL THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='No active pricing rule for this route'; END IF;

  SET v_freight=ROUND((v_base+v_weight*v_kg+v_volume*v_cbm)*v_season*v_demand,2);
  SET v_customs_amt=ROUND(v_freight*v_customs/100,2);
  SET v_insurance_amt=ROUND(v_freight*v_insurance/100,2);
  SET v_subtotal=v_freight+v_handling+v_customs_amt+v_insurance_amt;
  SET v_tax_amt=ROUND(v_subtotal*v_tax/100,2);
  SET v_total=v_subtotal+v_tax_amt;

  INSERT INTO shipment(shipment_no,consumer_id,seller_id,container_id,vessel_id,origin_port_id,dest_port_id,
    cargo_description,cargo_weight_kg,cargo_volume_cbm,quoted_price,status,etd,eta)
  VALUES(p_shipment_no,p_customer_id,p_seller_id,v_container_id,p_vessel_id,p_origin_port,p_dest_port,
    v_product_name,v_weight,v_volume,v_total,'BOOKED',p_etd,p_eta);
  SET v_shipment_id=LAST_INSERT_ID();

  INSERT INTO shipment_items(shipment_id,product_id,quantity,unit_price,weight_kg,volume_cbm,amount)
  VALUES(v_shipment_id,p_product_id,p_quantity,v_unit_price,v_weight,v_volume,p_quantity*v_unit_price);
  UPDATE stock SET reserved_qty=reserved_qty+p_quantity WHERE stock_id=v_stock_id;
  UPDATE containers SET status='ALLOCATED' WHERE container_id=v_container_id;

  INSERT INTO container_movements(shipment_id,container_id,status,port_id,event_time,remarks,updated_by)
  VALUES(v_shipment_id,v_container_id,'BOOKED',p_origin_port,NOW(),'Booking created',p_user_id);

  INSERT INTO billing_invoices(invoice_no,shipment_id,consumer_id,seller_id,sub_total,tax_amount,total_amount,issue_date,due_date)
  VALUES(p_invoice_no,v_shipment_id,p_customer_id,p_seller_id,v_subtotal,v_tax_amt,v_total,CURDATE(),p_due_date);
  SET v_invoice_id=LAST_INSERT_ID();
  INSERT INTO invoice_line_items(invoice_id,item_type,description,quantity,unit_price,amount) VALUES
    (v_invoice_id,'FREIGHT','Freight charge',1,v_freight,v_freight),
    (v_invoice_id,'HANDLING','Handling charge',1,v_handling,v_handling),
    (v_invoice_id,'CUSTOMS','Customs duty',1,v_customs_amt,v_customs_amt),
    (v_invoice_id,'INSURANCE','Insurance',1,v_insurance_amt,v_insurance_amt),
    (v_invoice_id,'TAX','Tax/GST',1,v_tax_amt,v_tax_amt);
  INSERT INTO audit_log(user_id,action,table_name,record_id,new_value)
  VALUES(p_user_id,'BOOKING_CREATED','shipment',v_shipment_id,JSON_OBJECT('shipment_no',p_shipment_no,'invoice_id',v_invoice_id,'total',v_total));
  COMMIT;
  SELECT v_shipment_id AS shipment_id,v_invoice_id AS invoice_id,v_container_id AS container_id,v_total AS invoice_total;
END$$

-- FR2: update shipment movement/status. Trigger writes movement history + audit.
